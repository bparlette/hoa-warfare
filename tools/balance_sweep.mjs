#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { Sim } from '../web/src/engine/sim.js';
import { MODES } from '../web/src/engine/modes.js';
import { MAPS, buildMap } from '../web/src/engine/map.js';
import { mulberry32 } from '../web/src/core/rng.js';

const root = new URL('..', import.meta.url);
const content = JSON.parse(readFileSync(new URL('data/hoa_content.json', root)));
const weapons = JSON.parse(readFileSync(new URL('data/weapons.json', root)));
const FACTIONS = Object.keys(content.factions).filter(f => content.factions[f].status !== 'draft');

function match({ mode = 'clash', map = 'culdesac', seed = 1, limit = 300, actor = i => ({ team: i % 2, faction: FACTIONS[i % FACTIONS.length] }), onStep } = {}) {
  const sim = new Sim({ rules: content.rules, weapons, rng: mulberry32(seed), mode, map: buildMap(map), timeLimit: limit });
  for (let i = 0; i < 12; i++) sim.addActor({ id: 'p' + i, name: 'P' + i, ...actor(i) });
  sim.start();
  let steps = 0;
  while (!sim.over && sim.time < limit + 100) {
    sim.step(1 / 60);
    const events = sim.drainEvents();
    onStep?.(sim, events, ++steps);
  }
  return sim;
}

const SEEDS = 20;
const results = [];

console.log('Starting 20-seed multi-seed balance sweep...');
for (const map of Object.keys(MAPS)) {
  for (const mode of Object.keys(MODES)) {
    if (mode === 'tutorial') continue;
    let team0Wins = 0, team1Wins = 0, ties = 0;
    let totalTime = 0;
    let totalStuck = 0;
    let totalScore0 = 0, totalScore1 = 0;

    for (let seed = 1; seed <= SEEDS; seed++) {
      let stuckThisMatch = 0;
      const sim = match({
        mode,
        map,
        seed,
        actor: i => ({ team: i % 2, faction: FACTIONS[(i + seed) % FACTIONS.length] }),
        onStep: (s, ev, n) => {
          if (n % 60 === 0) {
            for (const a of s.actors) {
              if (a.alive && s.blocked(a.pos.x, a.pos.z, a.pos.y)) stuckThisMatch++;
            }
          }
        }
      });

      totalTime += sim.time;
      totalStuck += stuckThisMatch;
      totalScore0 += sim.score[0];
      totalScore1 += sim.score[1];

      if (sim.score[0] > sim.score[1]) team0Wins++;
      else if (sim.score[1] > sim.score[0]) team1Wins++;
      else ties++;
    }

    const winPct0 = ((team0Wins / SEEDS) * 100).toFixed(1);
    const avgDuration = (totalTime / SEEDS).toFixed(1);
    results.push({
      map,
      mode,
      team0Wins,
      team1Wins,
      ties,
      winPct0: Number(winPct0),
      avgScore0: (totalScore0 / SEEDS).toFixed(1),
      avgScore1: (totalScore1 / SEEDS).toFixed(1),
      avgDuration: Number(avgDuration),
      totalStuck
    });
    console.log(`${map.padEnd(12)} ${mode.padEnd(18)} Win0: ${winPct0.padStart(5)}% (${team0Wins}-${team1Wins}-${ties}) AvgT: ${avgDuration.padStart(5)}s Stuck: ${totalStuck}`);
  }
}

writeFileSync(new URL('docs/launch/balance-data-20seeds.json', root), JSON.stringify(results, null, 2));

// Also generate markdown table
let md = '# 20-Seed Multi-Map & Multi-Mode Balance Sweep\n\n';
md += 'Generated by Haiku for Opus objective balancing.\n\n';
md += '| Map | Mode | Team 0 Win % | W - L - T | Avg Score (T0 - T1) | Avg Match Duration | Total Stuck Count |\n';
md += '| :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n';
for (const r of results) {
  md += `| \`${r.map}\` | \`${r.mode}\` | **${r.winPct0}%** | ${r.team0Wins}-${r.team1Wins}-${r.ties} | ${r.avgScore0} - ${r.avgScore1} | ${r.avgDuration}s | ${r.totalStuck} |\n`;
}
writeFileSync(new URL('docs/launch/balance-table.md', root), md);
console.log('Saved balance-data-20seeds.json and balance-table.md successfully!');
